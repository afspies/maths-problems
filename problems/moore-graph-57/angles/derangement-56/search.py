#!/usr/bin/env python3
r"""Exact gain-graph search for regular groups in the Moore graph construction.

The normalized instance has q = |H| vertices (the branches 2,...,k, where
k=q+1).  An oriented edge ij receives a nonidentity gain g_ij, with
g_ji=g_ij^{-1}.  Every vertex row is a permutation of H\{e}; triangle and
quadrilateral gains must be nonidentity.

The first row is fixed to the canonical ordering of H\{e}.  The solver is a
complete finite-domain backtracker with MRV, row-AllDifferent propagation,
and eager checks of every newly completed triangle and quadrilateral.  The
abelian obstruction is an optional exact presolver; --skip-abelian-obstruction
forces actual enumeration (useful for the C6 smoke test).
"""

